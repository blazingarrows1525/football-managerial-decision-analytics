"""StatsBomb Open Data client: cached, retried downloads with a per-file provenance record."""
from __future__ import annotations

import json
import logging
import pandas as pd
import time
from dataclasses import dataclass
from dataclasses import field
from datetime import datetime
from datetime import timezone
from pathlib import Path
from typing import Any

from src.config import Config, REAL_OPEN_DATA, USER_DATA
from src.data.provenance import sha256_bytes


def statsbomb_paths(competition_id: int | None = None, season_id: int | None = None,
                    match_id: int | None = None) -> dict[str, str]:
    """Relative paths of StatsBomb open-data resources (same layout locally and remotely)."""
    paths = {"competitions": "competitions.json"}
    if competition_id is not None and season_id is not None:
        paths["matches"] = f"matches/{competition_id}/{season_id}.json"
    if match_id is not None:
        paths["events"] = f"events/{match_id}.json"
        paths["lineups"] = f"lineups/{match_id}.json"
        paths["three_sixty"] = f"three-sixty/{match_id}.json"
    return paths

log = logging.getLogger("football_analytics.ingestion")


class DataUnavailableError(RuntimeError):
    """Raised when a resource is neither cached nor retrievable."""


@dataclass
class DataStore:
    """Reads StatsBomb-layout JSON from cache, the network, or a local folder.

    * REAL_OPEN_DATA: cache in ``data/raw/statsbomb``; download on cache miss.
    * USER_DATA: read-only from ``config.user_data_dir`` (same layout).
    * DEMO_SYNTHETIC: files generated by :mod:`synthetic` into ``data/raw/synthetic``.
    """

    config: Config
    offline: bool = False
    manifest: list[dict[str, Any]] = field(default_factory=list)

    def __post_init__(self) -> None:
        self.config.ensure_dirs()

    # ------------------------------------------------------------------ paths
    @property
    def root(self) -> Path:
        if self.config.data_mode == USER_DATA:
            p = Path(self.config.user_data_dir)
            return p if p.is_absolute() else self.config.project_root / p
        return self.config.raw_dir

    def _record(self, rel: str, url: str, path: Path | None, status: str, data: bytes | None,
                match_id: int | None, kind: str, from_cache: bool, error: str = "") -> None:
        self.manifest.append({
            "resource": kind,
            "relative_path": rel,
            "source_url": url,
            "local_path": str(path) if path else "",
            "match_id": match_id,
            "retrieved_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            # when the raw file was actually downloaded/written (cache hits keep the original time)
            "file_written_utc": (datetime.fromtimestamp(path.stat().st_mtime, timezone.utc).isoformat(timespec="seconds")
                                 if path is not None and path.exists() else ""),
            "bytes": len(data) if data is not None else 0,
            "sha256": sha256_bytes(data) if data is not None else "",
            "from_cache": from_cache,
            "status": status,
            "error": error,
        })

    # ------------------------------------------------------------------ fetch
    def _download(self, url: str) -> bytes:
        import requests  # imported lazily so offline tests never need it

        last_err: Exception | None = None
        for attempt in range(1, self.config.max_retries + 1):
            try:
                r = requests.get(url, timeout=self.config.request_timeout)
                if r.status_code == 404:
                    raise DataUnavailableError(f"404 Not Found: {url}")
                if r.status_code == 429 or r.status_code >= 500:
                    raise ConnectionError(f"HTTP {r.status_code}")
                r.raise_for_status()
                return r.content
            except DataUnavailableError:
                raise
            except Exception as exc:  # network errors, timeouts, rate limits
                last_err = exc
                wait = min(2 ** attempt, 20)
                log.warning("Attempt %s/%s failed for %s (%s); retrying in %ss",
                            attempt, self.config.max_retries, url, exc, wait)
                time.sleep(wait)
        raise DataUnavailableError(f"Failed after {self.config.max_retries} attempts: {url} ({last_err})")

    def get_json(self, rel: str, kind: str, match_id: int | None = None) -> Any:
        """Return parsed JSON for a relative resource path, caching raw bytes unchanged."""
        path = self.root / rel
        url = (f"{self.config.statsbomb_base_url}/{rel}" if self.config.data_mode == REAL_OPEN_DATA
               else f"file://{path}")
        if path.exists():
            data = path.read_bytes()
            self._record(rel, url, path, "ok", data, match_id, kind, from_cache=True)
        elif self.config.data_mode == REAL_OPEN_DATA and not self.offline:
            try:
                data = self._download(url)
            except DataUnavailableError as exc:
                self._record(rel, url, None, "failed", None, match_id, kind, False, str(exc))
                raise
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            self._record(rel, url, path, "ok", data, match_id, kind, from_cache=False)
        else:
            msg = f"Not cached and not downloadable in mode {self.config.data_mode} (offline={self.offline})"
            self._record(rel, url, None, "missing", None, match_id, kind, False, msg)
            raise DataUnavailableError(f"{msg}: {path}")
        try:
            return json.loads(data.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError) as exc:
            self.manifest[-1]["status"] = "malformed"
            self.manifest[-1]["error"] = str(exc)
            raise DataUnavailableError(f"Malformed JSON in {path}: {exc}") from exc

    # --------------------------------------------------------------- catalogue
    def competitions(self) -> pd.DataFrame:
        """The competition/season catalogue actually published by the source."""
        data = self.get_json(statsbomb_paths()["competitions"], "competitions")
        df = pd.DataFrame(data)
        keep = [c for c in ["competition_id", "season_id", "country_name", "competition_name",
                            "competition_gender", "competition_youth", "competition_international",
                            "season_name", "match_available", "match_available_360"] if c in df.columns]
        return df[keep].sort_values(["competition_name", "season_name"]).reset_index(drop=True)

    def matches_raw(self, competition_id: int, season_id: int) -> list[dict]:
        rel = statsbomb_paths(competition_id, season_id)["matches"]
        return self.get_json(rel, "matches")

    def match_files(self, match_ids: list[int], include_360: bool = False,
                    progress: bool = True) -> dict[int, dict[str, Any]]:
        """Fetch events + lineups (+ optional 360) per match. Failures are recorded, not fatal."""
        out: dict[int, dict[str, Any]] = {}
        n = len(match_ids)
        for i, mid in enumerate(match_ids, 1):
            paths = statsbomb_paths(match_id=mid)
            rec: dict[str, Any] = {}
            for kind in ("events", "lineups") + (("three_sixty",) if include_360 else ()):
                try:
                    rec[kind] = self.get_json(paths[kind], kind, match_id=mid)
                except DataUnavailableError as exc:
                    log.warning("match %s %s unavailable: %s", mid, kind, exc)
                    rec[kind] = None
            out[mid] = rec
            if progress and (i % 10 == 0 or i == n):
                print(f"  fetched {i}/{n} matches")
        return out

    def iter_match_files(self, match_ids: list[int], include_360: bool = False, progress: Any = None):
        """Yield ``(match_id, {"events": ..., "lineups": ...})`` one match at a time.

        Only one match's raw JSON is held in memory at once, which keeps the peak footprint small on hosted
        runtimes. ``progress`` is an optional callable ``(done, total, match_id)``.
        """
        n = len(match_ids)
        for i, mid in enumerate(match_ids, 1):
            paths = statsbomb_paths(match_id=mid)
            rec: dict[str, Any] = {}
            for kind in ("events", "lineups") + (("three_sixty",) if include_360 else ()):
                try:
                    rec[kind] = self.get_json(paths[kind], kind, match_id=mid)
                except DataUnavailableError as exc:
                    log.warning("match %s %s unavailable: %s", mid, kind, exc)
                    rec[kind] = None
            if progress is not None:
                progress(i, n, mid)
            yield mid, rec

    def three_sixty(self, match_id: int) -> list[dict] | None:
        """StatsBomb 360 freeze frames for one match (large optional file); ``None`` when not published."""
        try:
            return self.get_json(statsbomb_paths(match_id=match_id)["three_sixty"], "three_sixty", match_id=match_id)
        except DataUnavailableError as exc:
            log.warning("match %s 360 frames unavailable: %s", match_id, exc)
            return None

    def manifest_frame(self) -> pd.DataFrame:
        df = pd.DataFrame(self.manifest)
        if df.empty:
            return df
        # Several reads of the same file in one session -> keep the last record.
        return df.drop_duplicates(subset=["relative_path"], keep="last").reset_index(drop=True)


def select_matches(matches: list[dict], limit: int | None, focus_team: str | None = None) -> list[dict]:
    """Deterministically choose the analysed matches (chronological order).

    The selection is reported in the notebook so truncation is never silent.
    """
    ordered = sorted(matches, key=lambda m: (m.get("match_date", ""), m.get("kick_off") or "", m["match_id"]))
    if focus_team:
        involved = [m for m in ordered if focus_team in (m["home_team"]["home_team_name"],
                                                         m["away_team"]["away_team_name"])]
        if involved:
            ordered = involved
    return ordered if limit is None else ordered[:limit]


class LazyMatchFiles:
    """Mapping-like view over match files that loads each match only while it is being parsed."""

    def __init__(self, store: DataStore, match_ids: list[int], include_360: bool = False,
                 progress: Any = None) -> None:
        self.store, self.match_ids, self.include_360, self.progress = store, list(match_ids), include_360, progress

    def __len__(self) -> int:
        return len(self.match_ids)

    def items(self):
        return self.store.iter_match_files(self.match_ids, self.include_360, self.progress)
